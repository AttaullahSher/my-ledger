import { describe, expect, it } from 'vitest'
import { formatPhone, normalizePhone, phoneMatches } from '../src/lib/phone'

describe('mobile numbers in any format', () => {
  const cases: [string, string][] = [
    // UAE
    ['050 123 4567', '+971501234567'],
    ['0501234567', '+971501234567'],
    ['050-123-4567', '+971501234567'],
    ['(050) 123 4567', '+971501234567'],
    ['501234567', '+971501234567'],
    ['971501234567', '+971501234567'],
    ['+971 50 123 4567', '+971501234567'],
    ['+971-50-1234567', '+971501234567'],
    ['00971 50 123 4567', '+971501234567'],
    ['٠٥٠١٢٣٤٥٦٧', '+971501234567'],
    ['02 123 4567', '+97121234567'],
    // Pakistan
    ['0300 1234567', '+923001234567'],
    ['0300-1234567', '+923001234567'],
    ['03001234567', '+923001234567'],
    ['3001234567', '+923001234567'],
    ['92 300 1234567', '+923001234567'],
    ['+92 300 1234567', '+923001234567'],
    ['+92-300-1234567', '+923001234567'],
    ['0092 300 1234567', '+923001234567'],
    ['۰۳۰۰۱۲۳۴۵۶۷', '+923001234567'],
    // USA
    ['(212) 555-1234', '+12125551234'],
    ['212.555.1234', '+12125551234'],
    ['212-555-1234', '+12125551234'],
    ['1 212 555 1234', '+12125551234'],
    ['+1 (212) 555-1234', '+12125551234'],
    ['+1 212 555 1234 ext 22', '+12125551234'],
    // Others
    ['+44 7700 900123', '+447700900123'],
    ['0044 7700 900123', '+447700900123'],
    ['tel:+966 50 123 4567', '+966501234567'],
  ]
  it.each(cases)('%s → %s', (input, out) => expect(normalizePhone(input)).toBe(out))

  it('rejects things that are not phone numbers', () => {
    for (const bad of ['', '123', 'abc', '+12', '1234567890123456789']) expect(normalizePhone(bad)).toBeUndefined()
  })

  it('shows numbers nicely', () => {
    expect(formatPhone('+971501234567')).toBe('+971 50 123 4567')
    expect(formatPhone('+923001234567')).toBe('+92 300 1234567')
    expect(formatPhone('+12125551234')).toBe('+1 212 555 1234')
  })

  it('search finds a number however it is typed', () => {
    expect(phoneMatches('+971501234567', '050 123')).toBe(true)
    expect(phoneMatches('+923001234567', '0300')).toBe(true)
    expect(phoneMatches('+12125551234', '555-12')).toBe(true)
    expect(phoneMatches('+971501234567', '0300')).toBe(false)
  })
})
